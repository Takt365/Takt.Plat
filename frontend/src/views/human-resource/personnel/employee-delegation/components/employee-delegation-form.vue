<script setup lang="ts">
/**
 * 员工代理关系实体 独立记录所有代理场景维护表单 · 由 generate-vue-from-api 根据 types/api 生成
 * @module views/human-resource/personnel/employee-delegation/components
 */
import { reactive, watch, computed, ref } from 'vue'
import { useI18n } from 'vue-i18n'
import type { Rule } from 'ant-design-vue/es/form'
import type { EmployeeDelegationCreate } from '@/types/human-resource/personnel/employee-delegation'
import { useTenantStore } from '@/stores/identity/tenant'
import { useUserStore } from '@/stores/identity/user'

const { t } = useI18n()

const tenantStore = useTenantStore()
const userStore = useUserStore()

/**
 * 上下文隔离字段：租户 / 公司 / 公司默认语言（登录或公司切换注入，表单只读）
 * @param target 表单数据
 * @param force 为 true 时强制覆盖（新增态或公司切换）
 */
function applyScopeDefaults(target: Record<string, unknown>, force = false) {
  if (formFields.includes('tenantCode') && (force || !target.tenantCode)) {
    target.tenantCode = tenantStore.tenantCode
  }
  if (formFields.includes('companyCode') && (force || !target.companyCode)) {
    target.companyCode = tenantStore.companyCode
  }
  if (formFields.includes('companyDefaultCulture') && (force || !target.companyDefaultCulture)) {
    target.companyDefaultCulture = userStore.userInfo?.companyDefaultCulture ?? ''
  }
}
const formContentClass = computed(() => (formFields.length > 10 ? 'takt-form-content-rows-10' : 'takt-form-content-rows-5'))
const activeTab = ref('tab-0')
const formFields = ["tenantCode","companyCode","companyDefaultCulture","proxyEmployeeId","originalEmployeeId","delegationType","scopeType","scopeId","reason","startDate","endDate","extFieldJson","remark"]


interface Props {
  formData?: Partial<EmployeeDelegationCreate & { employeeDelegationId?: string }> | null
  loading?: boolean
}

const props = withDefaults(defineProps<Props>(), {
  formData: () => ({}),
  loading: false
})

const formRef = ref()
const formState = reactive<Record<string, any>>({})

watch(
  () => props.formData,
  (val) => {
    const next = val ? { ...val } : {}
    Object.keys(formState).forEach((k) => delete formState[k])

    applyScopeDefaults(next)
    Object.assign(formState, next)
  },
  { immediate: true, deep: true }
)

watch(
  () => [tenantStore.tenantCode, tenantStore.companyCode, userStore.userInfo?.companyDefaultCulture] as const,
  () => {
    const isCreate = !props.formData?.employeeDelegationId
    if (isCreate) {
      applyScopeDefaults(formState, true)
    }
  },
)

const rules = computed<Record<string, Rule[]>>(() => ({
  proxyEmployeeId: [
    {
      required: true,
      message: t('common.page.form.placeholder.required', { field: t('entity.employeeDelegation.proxyemployeeid') }),
      trigger: 'blur'
    }
  ],
  originalEmployeeId: [
    {
      required: true,
      message: t('common.page.form.placeholder.required', { field: t('entity.employeeDelegation.originalemployeeid') }),
      trigger: 'blur'
    }
  ],
  delegationType: [
    {
      required: true,
      message: t('common.page.form.placeholder.select', { field: t('entity.employeeDelegation.delegationtype') }),
      trigger: 'change'
    }
  ],
  scopeType: [
    {
      required: true,
      message: t('common.page.form.placeholder.required', { field: t('entity.employeeDelegation.scopetype') }),
      trigger: 'blur'
    }
  ],
  reason: [
    {
      required: true,
      message: t('common.page.form.placeholder.required', { field: t('entity.employeeDelegation.reason') }),
      trigger: 'blur'
    }
  ],
  startDate: [
    {
      required: true,
      message: t('common.page.form.placeholder.select', { field: t('entity.employeeDelegation.startdate') }),
      trigger: 'change'
    }
  ],
}))

async function validate() {
  await formRef.value?.validate()
  return formState
}

function getValues(): Record<string, any> {
  return { ...formState }
}

function resetFields() {
  formRef.value?.resetFields()
  Object.keys(formState).forEach((k) => delete formState[k])

  activeTab.value = 'tab-0'
}

defineExpose({ validate, getValues, resetFields })
</script>

